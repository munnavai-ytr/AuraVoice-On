'use client';

import * as React from 'react';
import {
  Mic,
  Play,
  Pause,
  RotateCcw,
  Trash2,
  Lock,
  Globe,
  Sparkles,
  AlertTriangle,
  Radio,
} from 'lucide-react';
import { Button } from '@/components/ui/Button';
import type { VoiceTemplate } from '@/types';

interface VoiceCardProps {
  voiceId: string;
  voiceTemplate?: VoiceTemplate | null;
  onReclone: () => void;
  onDelete: (voiceId: string) => Promise<void>;
  onTogglePrivacy?: (isPublic: boolean) => Promise<void>;
}

export function VoiceCard({
  voiceId,
  voiceTemplate,
  onReclone,
  onDelete,
  onTogglePrivacy,
}: VoiceCardProps) {
  const [isPlaying, setIsPlaying] = React.useState(false);
  const [audioError, setAudioError] = React.useState<string | null>(null);
  const [showRecloneModal, setShowRecloneModal] = React.useState(false);
  const [showDeleteModal, setShowDeleteModal] = React.useState(false);
  const [isDeleting, setIsDeleting] = React.useState(false);
  const [isPublic, setIsPublic] = React.useState(voiceTemplate?.is_public ?? false);
  const [isTogglingPrivacy, setIsTogglingPrivacy] = React.useState(false);

  const audioRef = React.useRef<HTMLAudioElement | null>(null);

  const voiceName = voiceTemplate?.voice_name || 'My Voice';
  const previewUrl = voiceTemplate?.preview_url;

  const handlePlayPreview = () => {
    setAudioError(null);
    if (!previewUrl) {
      setAudioError('Preview sample is being generated by ElevenLabs. Ready for studio use.');
      return;
    }

    if (!audioRef.current) {
      audioRef.current = new Audio(previewUrl);
      audioRef.current.onended = () => setIsPlaying(false);
      audioRef.current.onerror = () => {
        setIsPlaying(false);
        setAudioError('Could not stream preview audio. Voice is calibrated for synthesis.');
      };
    }

    if (isPlaying) {
      audioRef.current.pause();
      setIsPlaying(false);
    } else {
      audioRef.current.play().then(() => {
        setIsPlaying(true);
      }).catch(() => {
        setIsPlaying(false);
        setAudioError('Audio playback was prevented by browser autoplay policy.');
      });
    }
  };

  const handlePrivacyToggle = async () => {
    if (!onTogglePrivacy) return;
    try {
      setIsTogglingPrivacy(true);
      const nextVal = !isPublic;
      await onTogglePrivacy(nextVal);
      setIsPublic(nextVal);
    } catch (err) {
      console.error('Privacy toggle error:', err);
    } finally {
      setIsTogglingPrivacy(false);
    }
  };

  const handleDeleteConfirm = async () => {
    try {
      setIsDeleting(true);
      await onDelete(voiceId);
      setShowDeleteModal(false);
    } catch (err) {
      console.error('Delete error:', err);
    } finally {
      setIsDeleting(false);
    }
  };

  return (
    <div className="w-full max-w-2xl mx-auto space-y-6">
      {/* Primary Voice Management Card */}
      <div className="p-6 sm:p-8 rounded-2xl bg-[#0D1117] border border-[#1E293B] shadow-lg relative overflow-hidden">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-6 border-b border-[#1E293B]">
          <div className="flex items-center gap-4">
            <div className="w-14 h-14 rounded-2xl bg-[var(--indigo-glow)] border border-indigo-500/30 flex items-center justify-center shrink-0">
              <Radio className="w-7 h-7 text-[#6366F1]" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h3 className="text-xl font-bold text-[#F0F4FF] tracking-tight">{voiceName}</h3>
                <span className="px-2 py-0.5 rounded-full text-[10px] font-semibold bg-emerald-500/10 border border-emerald-500/20 text-[#10B981]">
                  Active
                </span>
              </div>
              <p className="text-xs text-[#8899B4] mt-1 font-mono">
                ID: {voiceId.substring(0, 16)}...
              </p>
            </div>
          </div>

          {/* Privacy Switch */}
          <button
            type="button"
            onClick={handlePrivacyToggle}
            disabled={isTogglingPrivacy}
            className="self-start sm:self-center flex items-center gap-2 px-3 py-1.5 rounded-xl bg-[#111827] border border-[#2D3F56] text-xs font-medium text-[#8899B4] hover:text-[#F0F4FF] transition-colors cursor-pointer"
          >
            {isPublic ? (
              <>
                <Globe className="w-3.5 h-3.5 text-indigo-400" />
                <span>Public Voice</span>
              </>
            ) : (
              <>
                <Lock className="w-3.5 h-3.5 text-amber-400" />
                <span>Private Model</span>
              </>
            )}
          </button>
        </div>

        {/* Audio feedback notice */}
        {audioError && (
          <div className="mt-4 p-3 rounded-xl bg-indigo-500/10 border border-indigo-500/20 text-xs text-[#818CF8] flex items-center gap-2">
            <Sparkles className="w-4 h-4 shrink-0" />
            <span>{audioError}</span>
          </div>
        )}

        {/* Action Buttons */}
        <div className="flex flex-wrap items-center gap-3 mt-6">
          <Button
            variant="primary"
            size="md"
            onClick={handlePlayPreview}
            className="h-[44px] px-5"
          >
            {isPlaying ? (
              <>
                <Pause className="w-4 h-4 mr-2" />
                Pause Preview
              </>
            ) : (
              <>
                <Play className="w-4 h-4 mr-2 fill-current" />
                Preview Voice
              </>
            )}
          </Button>

          <Button
            variant="secondary"
            size="md"
            onClick={() => setShowRecloneModal(true)}
            className="h-[44px] px-4"
          >
            <RotateCcw className="w-4 h-4 mr-2 text-[#8899B4]" />
            Re-clone Voice
          </Button>

          <Button
            variant="outline"
            size="md"
            onClick={() => setShowDeleteModal(true)}
            className="h-[44px] px-4 text-[#EF4444] border-red-500/20 hover:bg-red-500/10 hover:border-red-500/40 ml-auto"
          >
            <Trash2 className="w-4 h-4 mr-2" />
            Delete Model
          </Button>
        </div>
      </div>

      {/* Stats Summary Grid */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
        <div className="p-4 rounded-xl bg-[#0D1117] border border-[#1E293B]">
          <span className="text-xs text-[#8899B4]">Synthesis Quality</span>
          <p className="text-lg font-bold text-[#F0F4FF] mt-1">Studio HD</p>
          <span className="text-[11px] text-emerald-400">128kbps neural audio</span>
        </div>
        <div className="p-4 rounded-xl bg-[#0D1117] border border-[#1E293B]">
          <span className="text-xs text-[#8899B4]">Language Support</span>
          <p className="text-lg font-bold text-[#F0F4FF] mt-1">EN + বাংলা</p>
          <span className="text-[11px] text-[#8899B4]">Bilingual prosody</span>
        </div>
        <div className="p-4 rounded-xl bg-[#0D1117] border border-[#1E293B]">
          <span className="text-xs text-[#8899B4]">Model Status</span>
          <p className="text-lg font-bold text-[#10B981] mt-1">Ready for Studio</p>
          <span className="text-[11px] text-[#8899B4]">ElevenLabs Instant Clone</span>
        </div>
      </div>

      {/* Confirmation Modal for Re-cloning */}
      {showRecloneModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/70 backdrop-blur-sm animate-in fade-in">
          <div className="w-full max-w-md p-6 rounded-2xl bg-[#0D1117] border border-[#1E293B] shadow-2xl">
            <div className="w-12 h-12 rounded-xl bg-amber-500/10 border border-amber-500/20 flex items-center justify-center mb-4">
              <RotateCcw className="w-6 h-6 text-amber-400" />
            </div>
            <h4 className="text-lg font-bold text-[#F0F4FF] mb-2">Re-clone Your Voice?</h4>
            <p className="text-xs text-[#8899B4] leading-relaxed mb-6">
              Re-recording will guide you through the consent and reading studio again to generate
              a fresh voice calibration model.
            </p>
            <div className="flex gap-3 justify-end">
              <Button
                variant="ghost"
                size="md"
                onClick={() => setShowRecloneModal(false)}
              >
                Cancel
              </Button>
              <Button
                variant="primary"
                size="md"
                onClick={() => {
                  setShowRecloneModal(false);
                  onReclone();
                }}
              >
                Continue to Record
              </Button>
            </div>
          </div>
        </div>
      )}

      {/* Confirmation Modal for Deleting */}
      {showDeleteModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/70 backdrop-blur-sm animate-in fade-in">
          <div className="w-full max-w-md p-6 rounded-2xl bg-[#0D1117] border border-[#1E293B] shadow-2xl">
            <div className="w-12 h-12 rounded-xl bg-red-500/10 border border-red-500/25 flex items-center justify-center mb-4">
              <AlertTriangle className="w-6 h-6 text-[#EF4444]" />
            </div>
            <h4 className="text-lg font-bold text-[#F0F4FF] mb-2">Delete Voice Model?</h4>
            <p className="text-xs text-[#8899B4] leading-relaxed mb-6">
              This will permanently delete this voice clone from ElevenLabs and your Vocalis profile.
              You will need to record a new sample to generate audio.
            </p>
            <div className="flex gap-3 justify-end">
              <Button
                variant="ghost"
                size="md"
                disabled={isDeleting}
                onClick={() => setShowDeleteModal(false)}
              >
                Cancel
              </Button>
              <Button
                variant="danger"
                size="md"
                isLoading={isDeleting}
                onClick={handleDeleteConfirm}
              >
                Delete Model
              </Button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
